// Example routes computed by the Python router (api/examples): A->B alternatives between the demo area's hubs and
// suggested loops. The browser re-rates every route from its edge list and checks it gets the same numbers.
import { route, app, api, esc, onLeave, $ } from './core.js';
import { engine, routeFromTriples } from './engine.js';
import { MapView } from './map_view.js';
import { makeContext } from './context.js';
import { rate } from './rating.js';
import { routeCard, bindCards, cueList, safetyNote, ROUTE_COLORS } from './route_cards.js';
import { statDiffs } from './compare.js';

route('examples', async (args, query) => {
  const [eng, ex] = await Promise.all([engine(), api('/examples')]);
  const M = eng.model;
  const sets = [...ex.journeys.map(j => ({ title: j.title, routes: j.routes, kind: 'ab', start: j.start, end: j.end })),
    { title: `Suggested loops from ${ex.loops[0]?.title.split(':')[0] || 'the centre'}`, routes: ex.loops, kind: 'loop', start: ex.loops[0]?.start }];
  let si = Math.min(+query.set || 0, sets.length - 1), sel = 0;

  // re-rate every Python route in the browser (A->B alternatives are rated against their fastest option)
  const checks = sets.map(s => {
    const rs = s.routes.map(r => routeFromTriples(eng, r.edges, r.profile, r.kind, makeContext()));
    const fastest = s.kind === 'ab' ? Math.min(...rs.map(r => r.timeS)) : null;
    return rs.map((r, i) => {
      const st = rate(r, fastest);
      const ref = { ...s.routes[i].stats };
      if (s.kind === 'loop') { delete ref.distance_error_pct; delete ref.reuse_pct; }   // set by generate_loops, not rate()
      return statDiffs(st, ref);
    });
  });
  const total = checks.flat().length, agree = checks.flat().filter(d => !d.length).length;

  app().innerHTML = `
  <p class="kicker">${esc(ex.area)} · computed by Python</p>
  <h1>Example routes</h1>
  <p class="lead">Generated by the package's own <code>Router.alternatives</code> and <code>generate_loops</code> on the
  demo area, rated by <code>rating.rate</code>, with the turn-by-turn cue sheet from <code>directions.cue_sheet</code>.
  Start and end points are the area centre and the largest named parks in OpenStreetMap.</p>
  <p class="${agree === total ? 'ok' : 'warnc'} small">${agree === total ? '✓' : '✗'} Your browser re-rated all ${total} routes from their
  street lists with the JavaScript port and got ${agree === total ? 'exactly the same' : `the same numbers for ${agree}`} ratings.</p>
  <div class="seg sets" role="group" aria-label="Example">${sets.map((s, i) => `<button type="button" data-s="${i}"${i === si ? ' class="on"' : ''}>${esc(s.title)}</button>`).join('')}</div>
  <div id="map"></div>
  <div id="list"></div>
  ${safetyNote(M)}`;

  const map = new MapView($('#map'), eng, { height: 480 });
  onLeave(() => map.destroy());
  let routes = [];

  function show() {
    const s = sets[si];
    routes = s.routes.map(r => routeFromTriples(eng, r.edges, r.profile, r.kind));
    map.setRoutes(routes.map((r, i) => ({ coords: r.coords(), color: ROUTE_COLORS[i % ROUTE_COLORS.length], selected: i === sel })));
    map.setMarkers([{ lat: s.start[0], lon: s.start[1], label: 'A', color: '#7cff6b' },
      s.end && { lat: s.end[0], lon: s.end[1], label: 'B', color: '#ff6fd8' }].filter(Boolean));
    const r = s.routes[sel];
    $('#list').innerHTML = `<h2>${esc(s.title)}</h2>
      <div class="grid wide">${s.routes.map((x, i) => routeCard(x, i, M.lts_colors, { selected: i === sel,
        badge: checks[si][i].length ? '<span class="tag b">JS differs</span>' : '<span class="tag a" title="the browser re-rating matches Python">✓ JS</span>' })).join('')}</div>
      <h3>Directions: ${esc(r.title || r.profile_label)}</h3>${cueList(r.cues, M.lts_colors)}`;
    bindCards($('#list'), i => { sel = i; show(); });
  }
  document.querySelectorAll('[data-s]').forEach(b => b.addEventListener('click', () => {
    si = +b.dataset.s; sel = 0;
    document.querySelectorAll('[data-s]').forEach(x => x.classList.toggle('on', x === b));
    show();
    map.fit(routes.flatMap(r => r.coords()));
  }));
  show();
  map.fit(routes.flatMap(r => r.coords()));
});
